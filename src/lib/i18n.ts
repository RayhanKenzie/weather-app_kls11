const PHRASES = Object.entries(INDONESIAN).sort(([left], [right]) => right.length - left.length);

export function translateText(text: string, language: string): string {
  if (language === "English") return text;
  const exact = INDONESIAN[text];
  if (exact) return exact;

  return PHRASES.reduce((result, [source, translated]) => {
    return result.replace(new RegExp(source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g"), translated);
  }, text);
}